/**
 * Returns the dictionary for the requested locale with fallback to 'ar'.
 */
export function getTranslation(locale?: Locale): typeof translations['ar'] {
  return translations[locale === 'en' ? 'en' : 'ar'];
}

/**
 * Formats a date using Intl.DateTimeFormat according to active locale.
 */
export function formatDate(
  dateInput: Date | string | number | null | undefined, 
  locale: Locale = 'ar'
): string {
  if (!dateInput) return '';
  const d = new Date(dateInput);
  if (isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-YE' : 'en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  }).format(d);
}

/**
 * Localizes an arbitrary status string according to active locale.
 */
export function formatLocalizedStatus(status: string, locale: Locale = 'ar'): string {
  const t = getTranslation(locale);
  const key = `status_${(status || '').toUpperCase()}` as keyof typeof t;
  return (t[key] as string) || status;
}
